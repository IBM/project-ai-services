package com.ibm.aiservices.mock.service.common;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import com.ibm.aiservices.mock.http.Router;
import com.ibm.aiservices.mock.util.Json;

/**
 * Generates a minimal OpenAPI document from a router's route table, so Swagger UI pages served by the mock list every mocked operation.
 * <p>
 * The document describes paths, methods and path parameters only; request and response schemas are documented by the real services.
 */
public final class OpenApiDoc {

    private static final Pattern PATH_PARAM = Pattern.compile("\\{([^}*]+)\\*?}");

    private OpenApiDoc() {
    }

    /**
     * Builds the OpenAPI document.
     *
     * @param _title the API title
     * @param _version the API version
     * @param _router the router whose routes are described
     * @param _hidden path prefixes to leave out, for routes the real service hides from its schema
     * @return the OpenAPI document as a JSON-ready map
     */
    public static Map<String, Object> build(final String _title, final String _version, final Router _router, final String... _hidden) {
        final Map<String, Object> paths = new LinkedHashMap<String, Object>();
        for (final Router.Route route : _router.getRoutes()) {
            final String pattern = route.getPattern().replace("*}", "}");
            if (isHidden(pattern, _hidden)) {
                continue;
            }
            @SuppressWarnings("unchecked")
            Map<String, Object> operations = (Map<String, Object>) paths.get(pattern);
            if (null == operations) {
                operations = new LinkedHashMap<String, Object>();
                paths.put(pattern, operations);
            }
            final List<Object> parameters = new ArrayList<Object>();
            final Matcher matcher = PATH_PARAM.matcher(pattern);
            while (matcher.find()) {
                parameters.add(Json.obj("name", matcher.group(1), "in", "path", "required", Boolean.TRUE, "schema", Json.obj("type", "string")));
            }
            operations.put(route.getMethod().toLowerCase(Locale.ROOT), Json.obj("summary", route.getMethod() + " " + pattern, "parameters", parameters, "responses", Json.obj("200", Json.obj("description", "Successful Response"))));
        }
        return Json.obj("openapi", "3.1.0", "info", Json.obj("title", _title, "version", _version, "description", "Generated by the AI Services mock server."), "paths", paths);
    }

    /**
     * Returns whether a pattern falls under a hidden prefix.
     *
     * @param _pattern the route pattern
     * @param _hidden the hidden prefixes
     * @return {@code true} if hidden
     */
    private static boolean isHidden(final String _pattern, final String[] _hidden) {
        for (final String prefix : _hidden) {
            if (_pattern.startsWith(prefix)) {
                return true;
            }
        }
        return false;
    }
}
